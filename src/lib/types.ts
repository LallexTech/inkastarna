export type Match = {
  id: number;
  startsAt: string;
  location: string;
  finished: boolean;
  home: string;
  away: string;
  homeId: number;
  awayId: number;
  homeScore: number | null;
  awayScore: number | null;
  friendly?: boolean;
  includeInStats?: boolean;
};
export type Standing = {
  position: number;
  team: string;
  played: number;
  won: number;
  drawn: number;
  lost: number;
  goalsFor: number;
  goalsAgainst: number;
  difference: number;
  points: number;
};
export type League = {
  name: string;
  season: string;
  divisionId: number;
  teamId: number;
  fetchedAt: string;
  matches: Match[];
  standings: Standing[];
  scorers: { name: string; team: string; goals: number }[];
  scorersAvailable: boolean;
};
export type Player = {
  id: string;
  name: string;
  number: number | null;
  position: string;
  hasAccount?: boolean;
  goals: number;
  assists: number;
  appearances: number;
  photoUrl?: string | null;
  admin?: boolean;
  rootAdmin?: boolean;
};
export type Attendance = {
  matchId: number;
  userId: string;
  playerId?: string | null;
  name: string;
  status: "yes" | "maybe" | "no";
};
export type Formation = "1-2-1" | "2-2";
export type Lineup = { matchId: number; slots: (string | null)[]; formation: Formation };
export type TeamData = {
  inviteCode?: string;
  players: Player[];
  attendance: Attendance[];
  lineups: Lineup[];
  teamLeads: string[];
  teamAdmins: string[];
  admin: boolean;
  leader: boolean;
  userId: string;
  playerId: string | null;
  friendlyMatches: Match[];
  matchPresence: { matchId: number; playerId: string; status: "played" | "spectator" | "absent" }[];
  ballots: { matchId: number; open: boolean; closed: boolean }[];
  ratings: { matchId: number; playerId: string; average: number | null; winner: boolean }[];
  seasonRatings: { playerId: string; average: number | null; matches: number; motm: number }[];
  playerMatchStats: { matchId: number; playerId: string; goals: number; assists: number; played: boolean }[];
};
