import { getMigrations } from "better-auth/db/migration";
import { auth } from "../src/lib/auth";
import { db } from "../src/lib/db";

const migration = await getMigrations(auth.options);
await migration.runMigrations();
await db.query(`
  CREATE TABLE IF NOT EXISTS league_snapshot (
    id integer PRIMARY KEY CHECK (id=1), data jsonb NOT NULL, fetched_at timestamptz NOT NULL
  );
  CREATE TABLE IF NOT EXISTS player_profile (
    user_id text PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
    number integer CHECK (number BETWEEN 1 AND 99), position text NOT NULL DEFAULT 'Allround'
  );
  CREATE TABLE IF NOT EXISTS attendance (
    match_id integer NOT NULL, user_id text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    status text NOT NULL CHECK(status IN ('yes','maybe','no')), updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(match_id,user_id)
  );
  CREATE TABLE IF NOT EXISTS lineup (
    match_id integer PRIMARY KEY, slots jsonb NOT NULL, formation text NOT NULL DEFAULT '1-2-1', updated_by text NOT NULL REFERENCES "user"(id),
    updated_at timestamptz NOT NULL DEFAULT now(), CHECK(jsonb_array_length(slots)=5)
  );
  ALTER TABLE lineup ADD COLUMN IF NOT EXISTS formation text NOT NULL DEFAULT '1-2-1';
  CREATE TABLE IF NOT EXISTS team_leader (
    user_id text PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
    assigned_by text NOT NULL REFERENCES "user"(id),
    assigned_at timestamptz NOT NULL DEFAULT now()
  );
  CREATE TABLE IF NOT EXISTS player_match_stats (
    match_id integer NOT NULL, user_id text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    goals integer NOT NULL DEFAULT 0 CHECK(goals>=0), assists integer NOT NULL DEFAULT 0 CHECK(assists>=0),
    played boolean NOT NULL DEFAULT false, PRIMARY KEY(match_id,user_id)
  );
  CREATE TABLE IF NOT EXISTS roster (
    id text PRIMARY KEY, name text NOT NULL UNIQUE,
    user_id text UNIQUE REFERENCES "user"(id) ON DELETE SET NULL
  );
  CREATE TABLE IF NOT EXISTS player_stats (
    match_id integer NOT NULL, player_id text NOT NULL REFERENCES roster(id),
    goals integer NOT NULL DEFAULT 0 CHECK(goals>=0), assists integer NOT NULL DEFAULT 0 CHECK(assists>=0),
    played boolean NOT NULL DEFAULT false, PRIMARY KEY(match_id,player_id)
  );
  ALTER TABLE roster ADD COLUMN IF NOT EXISTS display_name text;
  UPDATE roster SET display_name=name WHERE display_name IS NULL;
  ALTER TABLE roster ALTER COLUMN display_name SET NOT NULL;
  CREATE TABLE IF NOT EXISTS roster_profile (
    player_id text PRIMARY KEY REFERENCES roster(id) ON DELETE CASCADE,
    number integer CHECK(number BETWEEN 1 AND 99),
    position text NOT NULL DEFAULT 'Allround',
    photo bytea,
    photo_type text,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((photo IS NULL) = (photo_type IS NULL))
  );
  INSERT INTO roster_profile(player_id,number,position)
    SELECT r.id,p.number,p.position FROM roster r JOIN player_profile p ON p.user_id=r.user_id
    ON CONFLICT(player_id) DO NOTHING;
  CREATE TABLE IF NOT EXISTS team_admin (
    user_id text PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
    assigned_by text NOT NULL REFERENCES "user"(id), assigned_at timestamptz NOT NULL DEFAULT now()
  );
  CREATE TABLE IF NOT EXISTS friendly_match (
    id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000),
    opponent text NOT NULL CHECK(length(opponent) BETWEEN 1 AND 100),
    starts_at timestamptz NOT NULL,
    finished boolean NOT NULL DEFAULT true,
    created_by text NOT NULL REFERENCES "user"(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(id)
  );
  ALTER TABLE friendly_match ADD COLUMN IF NOT EXISTS home_score integer;
  ALTER TABLE friendly_match ADD COLUMN IF NOT EXISTS away_score integer;
  ALTER TABLE friendly_match ADD COLUMN IF NOT EXISTS include_in_stats boolean NOT NULL DEFAULT false;
  DO $$ BEGIN
    ALTER TABLE friendly_match ADD CONSTRAINT friendly_match_home_score_check CHECK(home_score BETWEEN 0 AND 100);
  EXCEPTION WHEN duplicate_object THEN NULL; END; $$;
  DO $$ BEGIN
    ALTER TABLE friendly_match ADD CONSTRAINT friendly_match_away_score_check CHECK(away_score BETWEEN 0 AND 100);
  EXCEPTION WHEN duplicate_object THEN NULL; END; $$;
  CREATE TABLE IF NOT EXISTS match_presence (
    match_id integer NOT NULL,
    player_id text NOT NULL REFERENCES roster(id) ON DELETE CASCADE,
    status text NOT NULL CHECK(status IN ('played','spectator','absent')),
    updated_by text NOT NULL REFERENCES "user"(id), updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(match_id,player_id)
  );
  ALTER TABLE match_presence DROP CONSTRAINT IF EXISTS match_presence_status_check;
  ALTER TABLE match_presence ADD CONSTRAINT match_presence_status_check CHECK(status IN ('played','spectator','absent'));
  CREATE TABLE IF NOT EXISTS match_comment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id integer NOT NULL,
    author_user_id text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    body text NOT NULL CHECK(length(body) BETWEEN 1 AND 2000),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS match_comment_match_created_idx ON match_comment(match_id,created_at,id);
  CREATE TABLE IF NOT EXISTS match_ballot (
    match_id integer PRIMARY KEY,
    opened_by text NOT NULL REFERENCES "user"(id), opened_at timestamptz NOT NULL DEFAULT now(),
    closed_by text REFERENCES "user"(id), closed_at timestamptz
  );
  ALTER TABLE match_ballot ADD COLUMN IF NOT EXISTS motm_winner_id text REFERENCES roster(id) ON DELETE SET NULL;
  CREATE TABLE IF NOT EXISTS match_vote (
    match_id integer NOT NULL,
    voter_user_id text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    motm_player_id text REFERENCES roster(id) ON DELETE SET NULL,
    submitted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(match_id,voter_user_id)
  );
  CREATE TABLE IF NOT EXISTS match_rating (
    match_id integer NOT NULL, voter_user_id text NOT NULL,
    player_id text NOT NULL REFERENCES roster(id) ON DELETE CASCADE,
    stars integer NOT NULL CHECK(stars BETWEEN 1 AND 5),
    PRIMARY KEY(match_id,voter_user_id,player_id),
    FOREIGN KEY(match_id,voter_user_id) REFERENCES match_vote(match_id,voter_user_id) ON DELETE CASCADE
  );
  WITH motm_votes AS (
    SELECT v.match_id,v.motm_player_id,
      COUNT(DISTINCT v.voter_user_id)::int AS votes
    FROM match_vote v
    JOIN match_presence target ON target.match_id=v.match_id AND target.player_id=v.motm_player_id AND target.status='played'
    JOIN roster voter ON voter.user_id=v.voter_user_id
    JOIN match_presence vp ON vp.match_id=v.match_id AND vp.player_id=voter.id AND vp.status IN ('played','spectator')
    JOIN match_ballot b ON b.match_id=v.match_id AND b.closed_at IS NOT NULL AND b.motm_winner_id IS NULL
    WHERE v.motm_player_id IS NOT NULL
    GROUP BY v.match_id,v.motm_player_id
  ), stars_given AS (
    SELECT v.match_id,voter.id AS player_id,COALESCE(SUM(rating.stars),0)::int AS stars_given
    FROM match_vote v
    JOIN roster voter ON voter.user_id=v.voter_user_id
    JOIN match_presence vp ON vp.match_id=v.match_id AND vp.player_id=voter.id AND vp.status IN ('played','spectator')
    LEFT JOIN match_rating rating ON rating.match_id=v.match_id AND rating.voter_user_id=v.voter_user_id
    JOIN match_ballot b ON b.match_id=v.match_id AND b.closed_at IS NOT NULL AND b.motm_winner_id IS NULL
    GROUP BY v.match_id,voter.id
  ), ranked AS (
    SELECT mv.match_id,mv.motm_player_id,
      ROW_NUMBER() OVER(PARTITION BY mv.match_id ORDER BY mv.votes DESC,COALESCE(sg.stars_given,0) DESC,random()) AS position
    FROM motm_votes mv LEFT JOIN stars_given sg ON sg.match_id=mv.match_id AND sg.player_id=mv.motm_player_id
  )
  UPDATE match_ballot b SET motm_winner_id=r.motm_player_id
    FROM ranked r WHERE b.match_id=r.match_id AND r.position=1 AND b.motm_winner_id IS NULL;
  CREATE UNIQUE INDEX IF NOT EXISTS unique_player_account_name ON "user"(lower(name));
`);
const initialRoster = (process.env.INITIAL_ROSTER ?? "")
  .split(",")
  .map((x) => x.trim())
  .filter(Boolean);
for (const name of initialRoster)
  await db.query(
    "INSERT INTO roster(id,name,display_name) VALUES($1,$2,$2) ON CONFLICT DO NOTHING",
    [name.toLowerCase(), name],
  );
console.log("Auth- och lagtabeller är uppdaterade.");
await db.end();
